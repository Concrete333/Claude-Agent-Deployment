"""Mechanical checks for answer.json, derived from TASK.md only.

Run from the task directory: python -B check.py .
Passing these checks does not establish that decisions or explanations are
correct; it only shows the file meets the stated mechanical contract.
Do not edit this file. Its hash is recorded in the trial manifest.
"""
import hashlib
import json
import re
import sys
from pathlib import Path

MIN_EXPLANATION_WORDS = 15
MAX_EXPLANATION_WORDS = 80
MIN_QUOTE_WORDS = 4
MAX_QUOTE_WORDS = 100
MAX_QUOTE_WORDS_PER_RECORD = 160
MAX_CITED_LINES = 3
FROZEN = None  # replaced at preparation time with {"TASK.md": sha256, "threads/ISSUE-001.md": sha256, ...}


def normalize(text):
    return ' '.join(text.split())


def sha(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def check(root):
    root = Path(root)
    errors = []
    frozen = FROZEN or {}
    for rel, digest in frozen.items():
        p = root / rel
        if not p.is_file() or sha(p) != digest:
            errors.append(rel + ': missing or changed')
    ids = sorted(p.stem for p in (root / 'threads').glob('ISSUE-*.md'))
    if frozen:
        ids = sorted(Path(k).stem for k in frozen if k.startswith('threads/'))
    try:
        answer = json.loads((root / 'answer.json').read_text(encoding='utf-8-sig'))
    except (OSError, ValueError) as exc:
        return {'pass': False, 'errors': ['answer.json unreadable: ' + str(exc)]}
    if not isinstance(answer, dict) or set(answer) != {'release', 'assessed_at', 'records'}:
        errors.append('top-level keys must be exactly release, assessed_at, records')
        return {'pass': False, 'errors': errors}
    if answer.get('release') != '4.0' or answer.get('assessed_at') != '2031-06-30':
        errors.append('release must be "4.0" and assessed_at "2031-06-30"')
    records = answer.get('records')
    if not isinstance(records, list):
        return {'pass': False, 'errors': errors + ['records must be a list']}
    if [r.get('id') if isinstance(r, dict) else None for r in records] != ids:
        errors.append('records must contain every thread ID exactly once, sorted by ID')
    for row in records:
        if not isinstance(row, dict):
            errors.append('record is not an object')
            continue
        ident = row.get('id', '?')
        if set(row) != {'id', 'disposition', 'explanation', 'evidence'}:
            errors.append(f'{ident}: record keys must be exactly id, disposition, explanation, evidence')
        if row.get('disposition') not in ('required', 'conditional', 'none', 'unresolved'):
            errors.append(f'{ident}: disposition must be required, conditional, none or unresolved')
        expl = row.get('explanation')
        if not isinstance(expl, str) or not MIN_EXPLANATION_WORDS <= len(expl.split()) <= MAX_EXPLANATION_WORDS:
            errors.append(f'{ident}: explanation must be {MIN_EXPLANATION_WORDS}..{MAX_EXPLANATION_WORDS} words')
        src = root / 'threads' / f'{ident}.md'
        if not src.is_file():
            errors.append(f'{ident}: no matching thread file')
            continue
        lines = src.read_text(encoding='utf-8').splitlines()
        evidence = row.get('evidence')
        if not isinstance(evidence, list) or not evidence:
            errors.append(f'{ident}: evidence must be a non-empty list')
            continue
        total = 0
        for i, cite in enumerate(evidence, 1):
            tag = f'{ident} evidence[{i}]'
            if not isinstance(cite, dict) or set(cite) != {'line_start', 'line_end', 'quote'}:
                errors.append(tag + ': keys must be exactly line_start, line_end, quote')
                continue
            start, end, quote = cite['line_start'], cite['line_end'], cite['quote']
            if type(start) is not int or type(end) is not int or not 1 <= start <= end <= len(lines):
                errors.append(tag + ': line_start/line_end must be integers within the file, start <= end')
                continue
            if end - start + 1 > MAX_CITED_LINES:
                errors.append(tag + f': cited span must be at most {MAX_CITED_LINES} lines')
            if not isinstance(quote, str):
                errors.append(tag + ': quote must be a string')
                continue
            words = len(quote.split())
            total += words
            if not MIN_QUOTE_WORDS <= words <= MAX_QUOTE_WORDS:
                errors.append(tag + f': quote must be {MIN_QUOTE_WORDS}..{MAX_QUOTE_WORDS} words')
            if re.search(r'\.\.\.|…|\[|\]', quote):
                errors.append(tag + ': quote must be verbatim; no ellipses or bracketed insertions')
            if normalize(quote) not in normalize('\n'.join(lines[start - 1:end])):
                errors.append(tag + ': quote not found verbatim (whitespace-normalized) within the cited lines')
        if total > MAX_QUOTE_WORDS_PER_RECORD:
            errors.append(f'{ident}: quoted words exceed {MAX_QUOTE_WORDS_PER_RECORD}')
    return {'pass': not errors, 'records': len(records), 'errors': errors,
            'note': 'Mechanical contract only; decisions and explanations are not assessed here.'}


if __name__ == '__main__':
    result = check(sys.argv[1] if len(sys.argv) > 1 else '.')
    print(json.dumps(result, indent=2))
    raise SystemExit(0 if result['pass'] else 1)
